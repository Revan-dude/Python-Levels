num1 = float(input("Gib die erste Zahl ein: "))
num2 = float(input("Gib die zweite Zahl ein: "))

difference = num1 - num2;
sum = num1 + num2;
multiplication = num1 * num2;
division = num1 / num2;
wholeNumberDivision = num1 // num2;

print(f"Die Differenz der beiden Zahlen beträgt {difference}.");
print(f"Die Summe der beiden Zahlen beträgt {sum}.");
print(f"Das Produkt der beiden Zahlen beträgt {multiplication}.");
print(f"Die Division der beiden Zahlen beträgt {division}.");
print(f"Die Ganzzahldivision der beiden Zahlen beträgt {wholeNumberDivision}.");



